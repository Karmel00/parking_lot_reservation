-- Parking Lot Reservation
-- PostgreSQL schema: users, parkings, parking_spots, reservations
--
-- Rezerwacje traktujemy jako przedziały [start_time, end_time):
-- rezerwacja kończąca się o 12:00 nie koliduje z rezerwacją
-- rozpoczynającą się o 12:00.

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- 1. Użytkownicy
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Parkingi
-- Przykładowe identyfikatory: P, D, S, G, M, H.
CREATE TABLE IF NOT EXISTS parkings (
    id VARCHAR(10) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    address TEXT NOT NULL,
    district VARCHAR(100),
    city VARCHAR(100) NOT NULL,
    price_per_hour NUMERIC(10, 2) NOT NULL CHECK (price_per_hour >= 0),
    total_spots INTEGER NOT NULL CHECK (total_spots >= 0),
    features JSONB NOT NULL DEFAULT '[]'::jsonb,
    highlight TEXT,
    illustration VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. Konkretne miejsca parkingowe
-- id jest technicznym kluczem głównym.
-- spot_code jest unikalnym identyfikatorem biznesowym, np. P001.
CREATE TABLE IF NOT EXISTS parking_spots (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parking_id VARCHAR(10) NOT NULL
        REFERENCES parkings(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    spot_number INTEGER NOT NULL CHECK (spot_number > 0),
    spot_code VARCHAR(10) GENERATED ALWAYS AS
        (parking_id || LPAD(spot_number::TEXT, 3, '0')) STORED,
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'maintenance')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_parking_spots_parking_number UNIQUE (parking_id, spot_number),
    CONSTRAINT uq_parking_spots_spot_code UNIQUE (spot_code)
);

CREATE INDEX IF NOT EXISTS idx_parking_spots_parking_id
    ON parking_spots(parking_id);

-- 4. Rezerwacje
-- Frontend/API przekazuje spot_code (np. P001).
-- reservations.parking_spot_id przechowuje ten kod bezpośrednio,
-- jako FK do parking_spots.spot_code (nie do parking_spots.id).
CREATE TABLE IF NOT EXISTS reservations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NULL
        REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    parking_spot_id VARCHAR(10) NOT NULL
        REFERENCES parking_spots(spot_code) ON UPDATE CASCADE ON DELETE RESTRICT,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    price NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (price >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_reservations_time CHECK (end_time > start_time),

    -- Blokuje nakładające się aktywne rezerwacje tego samego kodu miejsca.
    -- Rezerwacje anulowane nie blokują kolejnych rezerwacji.
    CONSTRAINT ex_reservations_no_active_overlap
        EXCLUDE USING GIST (
            parking_spot_id WITH =,
            TSTZRANGE(start_time, end_time, '[)') WITH &&
        )
        WHERE (status = 'active')
);

CREATE INDEX IF NOT EXISTS idx_reservations_user_id
    ON reservations(user_id);

CREATE INDEX IF NOT EXISTS idx_reservations_parking_spot_id
    ON reservations(parking_spot_id);

CREATE INDEX IF NOT EXISTS idx_reservations_active_time
    ON reservations(start_time, end_time)
    WHERE status = 'active';